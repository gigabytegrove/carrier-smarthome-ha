#!/usr/bin/env python3
"""Create a reproducible GraphQL operation catalog from extracted APK evidence.

Input is the sanitized JSON index and exact per-operation documents generated by
analyze_xapk.py. It never executes GraphQL, authenticates, or contacts Carrier.
"""
from __future__ import annotations
import argparse
from collections import Counter
import json
from pathlib import Path
import re

OPERATION = re.compile(r'^\s*(query|mutation|fragment)\s+([A-Za-z_][A-Za-z_0-9]*)\s*(?:\(([^)]*)\))?', re.S)
VARIABLE = re.compile(r'\$([A-Za-z_][A-Za-z_0-9]*)\s*:\s*(\[?[A-Za-z_][A-Za-z_0-9]*!?\]?!?)')


def catalog(index: list[dict], root: Path) -> list[dict]:
    outputs = []
    for item in index:
        src = root / item['path']
        content = src.read_text(encoding='utf-8')
        head = OPERATION.match(content)
        if item['standalone_document'] and not head:
            raise ValueError(f'Invalid standalone document: {src}')
        if head and (head.group(1), head.group(2)) != (item['type'], item['name']):
            raise ValueError(f'Unexpected GraphQL operation: {src}')
        variables = [{'name': name, 'type': kind} for name, kind in VARIABLE.findall(head.group(3) or '')] if head else []
        outputs.append({'name': item['name'], 'kind': item['type'],
                        'family': item['family'], 'hermes_string_id': item['hermes_string_id'],
                        'document_path': item['path'], 'standalone_document': item['standalone_document'],
                        'variables': variables})
    return outputs


def summarize(items: list[dict]) -> str:
    counts = Counter((i['family'], i['kind']) for i in items)
    sections = ['# Carrier SmartHome 1.2.42 — GraphQL inventory', '',
                'Source: user-supplied XAPK, offline Hermes string-table extraction. These are **document definitions**, not authenticated API results.', '',
                f'- {len(items)} recovered GraphQL definitions',
                f'- {sum(i["standalone_document"] for i in items)} standalone document strings',
                f'- {sum(not i["standalone_document"] for i in items)} partial/unreliable fragments (not safe to invoke)', '',
                '## Inventory by domain', '', '| Family | Queries | Mutations | Fragments |',
                '|---|---:|---:|---:|']
    for family in sorted({i['family'] for i in items}):
        sections.append(f'| {family} | {counts[(family,"query")]} | {counts[(family,"mutation")]} | {counts[(family,"fragment")]} |')
    sections += ['', '## Relevant entry-level operations', '', '| Operation | Type | Variables from APK |', '|---|---|---|']
    for item in sorted((x for x in items if x['family'] == 'entry_level'), key=lambda x: (x['kind'], x['name'])):
        variables = ', '.join(f'`{v["name"]}: {v["type"]}`' for v in item['variables']) or 'none'
        sections.append(f'| `{item["name"]}` | {item["kind"]} | {variables} |')
    sections += ['', '## Limitations', '',
                 '- GraphQL input object names are available; their complete field schemas may not be. Never invent required arguments.',
                 '- The presence of an operation in a universal Carrier app does not show it works for TSTATCCEWF-01.',
                 '- LocalControl/MQTT strings are separate evidence; they do not establish any specific device protocol.',
                 '- The exact Carrier SmartHome GraphQL hostname and login flow remain unconfirmed until verified.', '']
    return '\n'.join(sections)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-root', type=Path, default=Path(__file__).resolve().parent)
    args = parser.parse_args()
    root = args.source_root
    raw = json.loads((root / 'graphql-index.json').read_text(encoding='utf-8'))
    output = catalog(raw, root)
    (root / 'graphql-catalog.json').write_text(json.dumps(output, indent=2) + '\n', encoding='utf-8')
    (root / 'GRAPHQL_CATALOG.md').write_text(summarize(output), encoding='utf-8')
    print('Verified documents:', len(output), 'entry-level:', sum(x['family']=='entry_level' for x in output))


if __name__ == '__main__':
    main()
